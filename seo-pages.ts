/**
 * WHAT EACH BUILDER'S PAGE SAYS TO A CRAWLER (#1383, ADR-W-085) — the one table every Vite config
 * passes to `shell/seo/seoPlugin`.
 *
 * Build tooling, like the configs themselves: it is the one place that knows all four products, so
 * `shell/` never has to. Three sources, none of them new judgement:
 *
 *  - **title and description** — the operator-approved wording (#1383, draft v2, ruled 2026-09-24:
 *    Hebrew only, «4 ו-5 יחידות» on all four, «תרגול» and «חינם» kept). Change them only with a ruling;
 *  - **the URL** — `products.json`, so canonical, sitemap and the share store cannot disagree;
 *  - **the examples** — each product's catalog rows marked `featured`, which are the operator's own
 *    choice of what a student is shown first (#1347). A catalog edit updates the page with no edit here.
 *
 * The images (icon, 180 px touch icon, 1200×630 preview) live beside each product's code in `seo/`
 * and are regenerated by `scripts/render-icons.mjs` / `scripts/render-og.mjs`, never edited.
 */
