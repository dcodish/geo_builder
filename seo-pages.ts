/** The featured rows of a catalog, as the page shows them. */
export function featuredExamples(rows: readonly { he: string; descHe?: string; featured?: true }[]): SeoExample[] {
  return rows.filter((r) => r.featured).map((r) => ({ text: r.he, ...(r.descHe ? { note: r.descHe } : {}) }));
}

type ProductId = '2d' | '3d' | 'complex' | 'analytic';
const products = registry.products as { id: string; url?: string; label?: string }[];
/** The production URL of a builder, from the registry — absolute, trailing slash. */
export function productUrl(id: ProductId): string {
  const p = products.find((x) => x.id === id);
  if (!p?.url) throw new Error(`seo: products.json has no url for "${id}"`);
  return `${ORIGIN}${p.url}`;
}

