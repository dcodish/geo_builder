const ROOT = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
const asset = (dir: string, f: string) => path.join(ROOT, dir, 'seo', f);
const optional = (p: string) => {
  try {
    return readFileSync(p);
  } catch {
    return undefined;
  }
};

/** The table the plugin takes: entry HTML file → its page and assets. */
export function seoPages(): Record<string, SeoEntry> {
  const out: Record<string, SeoEntry> = {};
  for (const c of COPY) {
    const url = productUrl(c.id);
    const og = optional(asset(c.dir, 'og.png'));
    out[c.entry] = {
      page: {
        url,
        // The approved wording EXACTLY — no «| themathbible» suffix: v2 dropped it, and it would push
        // every title past the ~60 characters Google shows. `og:site_name` carries the site instead.
        title: c.title,
        description: c.description,
        siteName: SITE,
        name: NAMES[c.id],
        howToHeading: 'איך זה עובד',
        howTo: c.howTo,
        examplesHeading: 'דוגמאות למה אפשר לכתוב',
        examples: c.examples,
        linksHeading: 'עוד כלים',
        links: [
          ...COPY.filter((o) => o.id !== c.id).map((o) => ({ href: productUrl(o.id), label: NAMES[o.id] })),
          { href: HOME, label: 'themathbible.com — כל הכלים והחוברות' },
        ],
        footer: 'חינם, בלי הרשמה · ד״ר דוד קודיש',
        loading: 'הכלי נטען…',
        jsonLd: [
          {
            '@context': 'https://schema.org',
            '@type': 'WebApplication',
            name: NAMES[c.id],
            url,
            description: c.description,
            inLanguage: 'he',
            applicationCategory: 'EducationalApplication',
            operatingSystem: 'Any',
            browserRequirements: 'Requires JavaScript',
            isAccessibleForFree: true,
            offers: { '@type': 'Offer', price: '0', priceCurrency: 'ILS' },
            educationalLevel: 'בגרות במתמטיקה — 4 ו-5 יחידות',
            audience: { '@type': 'EducationalAudience', educationalRole: 'student' },
            author: AUTHOR,
            ...(og ? { image: `${url}seo/og.png` } : {}),
          },
        ],
      },
      assets: {
        iconSvg: readFileSync(asset(c.dir, 'icon.svg'), 'utf8'),
        touchPng: readFileSync(asset(c.dir, 'apple-touch-icon.png')),
        ...(og ? { ogPng: og } : {}),
      },
    };
  }
  return out;
}
